// Writes src/lib/phoneUploadGlyphs.js — the Files tab's file-type icons
// (components/fileGlyph: ExtGlyph, the ones the Debug tab's "File type icons"
// shows) as STATIC markup, for the phone upload page, which stands alone and
// cannot run React. One rendered icon per category, the extension → category
// table, and fileGlyph.css itself.
//
// Run when an icon or a category changes in fileGlyph.jsx / fileGlyph.css:
//   node scripts/build-phone-glyphs.mjs
// (build-upload-page.mjs runs it too, so a release always carries the current set.)

import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build } from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'src', 'lib', 'phoneUploadGlyphs.js');

// One sample extension per category ExtGlyph draws.
const SAMPLES = { pdf: 'pdf', doc: 'docx', xls: 'xlsx', ppt: 'pptx', zip: 'zip', img: 'jpg', vid: 'mp4', aud: 'mp3', txt: 'txt', collection: 'dvc', gen: 'xyz' };
// Every extension extCategory names (the Debug tab's FILE_TYPES).
const EXTS = ['pdf', 'doc', 'docx', 'docm', 'dot', 'dotx', 'dotm', 'rtf', 'odt', 'pages', 'xls', 'xlsx', 'xlsm', 'xlsb', 'xlt', 'xltx', 'xltm', 'csv', 'ods', 'numbers',
  'ppt', 'pptx', 'pptm', 'pps', 'ppsx', 'ppsm', 'pot', 'potx', 'potm', 'odp', 'key', 'jpg', 'jpeg', 'png', 'gif', 'webp', 'svg', 'heic', 'bmp', 'tif', 'tiff', 'psd', 'ai',
  'mp4', 'mov', 'avi', 'mkv', 'webm', 'm4v', 'mp3', 'wav', 'm4a', 'aac', 'ogg', 'oga', 'flac', 'opus', 'wma', 'aif', 'aiff', 'txt', 'md', 'log', 'zip', 'rar', '7z', 'tar', 'gz', 'dvc'];

const entry = `
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { ExtGlyph, extCategory } from ${JSON.stringify(path.join(root, 'src/components/fileGlyph.jsx').replace(/\\/g, '/'))};
const glyphs = {};
for (const [cat, ext] of Object.entries(${JSON.stringify(SAMPLES)})) glyphs[cat] = renderToStaticMarkup(React.createElement(ExtGlyph, { ext }));
const cats = {};
for (const e of ${JSON.stringify(EXTS)}) { const c = extCategory(e); if (glyphs[c] && c !== 'gen') cats[e] = c; }
export default { glyphs, cats };
`;

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'dvx-glyphs-'));
// Bundled INSIDE the repo so the externals (react) resolve from node_modules.
const bundle = path.join(root, 'node_modules', '.cache', 'dvx-phone-glyphs.mjs');
fs.mkdirSync(path.dirname(bundle), { recursive: true });
await build({
  stdin: { contents: entry, resolveDir: root, loader: 'jsx' },
  bundle: true, platform: 'node', format: 'esm', outfile: bundle, jsx: 'automatic', logLevel: 'error',
  loader: { '.css': 'empty' },
  external: ['react', 'react-dom', 'react-dom/*', 'react/*'],
  // fileGlyph only takes two MIME constants from lib/thumbnails; the rest of
  // that module is browser code.
  plugins: [{
    name: 'stub-thumbnails',
    setup(b) {
      b.onResolve({ filter: /lib\/thumbnails$/ }, () => ({ path: 'thumbnails', namespace: 'stub' }));
      b.onLoad({ filter: /.*/, namespace: 'stub' }, () => ({
        contents: "export const DOCX_MIME = 'application/vnd.openxmlformats-officedocument.wordprocessingml.document'; export const PPTX_MIME = 'application/vnd.openxmlformats-officedocument.presentationml.presentation';",
        loader: 'js',
      }));
    },
  }],
});
const { default: data } = await import(pathToFileURL(bundle).href);
fs.rmSync(tmp, { recursive: true, force: true });
fs.rmSync(bundle, { force: true });

const css = fs.readFileSync(path.join(root, 'src/components/fileGlyph.css'), 'utf8')
  .replace(/\/\*[\s\S]*?\*\//g, '').replace(/\n\s*\n+/g, '\n').trim();

const file = `// GENERATED by scripts/build-phone-glyphs.mjs — do not edit by hand.
// The Files tab's file-type icons (components/fileGlyph ExtGlyph) as static
// markup for the phone upload page (lib/phoneUploadPage), which cannot run
// React: one icon per category, extension → category, and fileGlyph.css.

export const PHONE_GLYPHS = ${JSON.stringify(data.glyphs, null, 2)};

export const PHONE_GLYPH_CATS = ${JSON.stringify(data.cats)};

export const PHONE_GLYPH_CSS = ${JSON.stringify(css)};
`;
fs.writeFileSync(out, file);
console.log(`phone glyphs: ${Object.keys(data.glyphs).length} icons, ${Object.keys(data.cats).length} extensions → ${path.relative(root, out)}`);
